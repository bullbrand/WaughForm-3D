// Embeds the Anthropic SDK browser bundle (vendor/anthropic-sdk) into WaughForm_3D.html, for the optional
// Claude look-up in the Parts Library. Run from the "claude code" folder:   node tools\embed-anthropic.js
// © 2026 David John Waugh. The SDK itself is Apache-2.0 licensed (vendor/anthropic-sdk/LICENSE).
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const html = path.join(root, 'WaughForm_3D.html');
const js = fs.readFileSync(path.join(root, 'vendor', 'anthropic-sdk', 'anthropic-sdk.js'), 'utf8');
if (js.includes('</script')) throw new Error('anthropic-sdk.js contains </script');

const block = '<!--ANTHROPIC-START-->\n' +
  '<!-- Anthropic SDK (@anthropic-ai/sdk, Apache License 2.0), embedded for the optional Claude look-up. Generated by tools/embed-anthropic.js -->\n' +
  `<script>${js}</script>\n` +
  '<!--ANTHROPIC-END-->';

let page = fs.readFileSync(html, 'utf8');
const re = /<!--ANTHROPIC-START-->[\s\S]*?<!--ANTHROPIC-END-->/;
if (!re.test(page)) throw new Error('markers <!--ANTHROPIC-START--> / <!--ANTHROPIC-END--> not found in WaughForm_3D.html');
page = page.replace(re, () => block);
fs.writeFileSync(html, page);
console.log(`Embedded Anthropic SDK: ${(js.length / 1024).toFixed(0)} KB`);
