// Embeds the Manifold geometry engine (vendor/manifold-3d) into WaughForm_3D.html so the app needs no
// internet and no extra files. Run from the "claude code" folder:   node tools\embed-manifold.js
// © 2026 David John Waugh. Manifold itself is Apache-2.0 licensed (vendor/manifold-3d/LICENSE).
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const html = path.join(root, 'WaughForm_3D.html');
const dir = path.join(root, 'vendor', 'manifold-3d');

let js = fs.readFileSync(path.join(dir, 'manifold.js'), 'utf8');
// The loader is an ES module; turn it into a plain script that sets window.ManifoldModule.
js = js.replace(/export\s+default\s+Module\s*;?\s*$/, '');
js = js.split('import.meta.url').join('""');
if (/import\.meta|export default/.test(js)) throw new Error('manifold.js: unexpected module syntax left');
if (js.includes('</script')) throw new Error('manifold.js contains </script');
const version = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8')).version;
const wasm = fs.readFileSync(path.join(dir, 'manifold.wasm')).toString('base64');

const block = '<!--MANIFOLD-START-->\n' +
  `<!-- Manifold ${version} geometry engine (Apache-2.0, https://github.com/elalish/manifold), embedded for offline use. Generated by tools/embed-manifold.js -->\n` +
  `<script type="application/octet-stream" id="manifold-wasm">${wasm}</script>\n` +
  `<script>window.ManifoldModule=(function(){${js}\nreturn Module;})();</script>\n` +
  '<!--MANIFOLD-END-->';

let page = fs.readFileSync(html, 'utf8');
const re = /<!--MANIFOLD-START-->[\s\S]*?<!--MANIFOLD-END-->/;
if (!re.test(page)) throw new Error('markers <!--MANIFOLD-START--> / <!--MANIFOLD-END--> not found in WaughForm_3D.html');
page = page.replace(re, () => block);
fs.writeFileSync(html, page);
console.log(`Embedded Manifold ${version}: ${(js.length / 1024).toFixed(0)} KB script + ${(wasm.length / 1024).toFixed(0)} KB wasm (base64)`);
